import { createHash } from "node:crypto";
import sharp from "sharp";
import type { ContentReference, QuizPackContent } from "../content";
import { DEFAULT_COMPATIBILITY_POLICY } from "../compatibility";
import type { QuizPackManifest } from "../manifest";

export interface SyntheticFixture {
  content: QuizPackContent;
  contentBytes: Uint8Array;
  manifest: QuizPackManifest;
  assets: { path: string; bytes: Uint8Array }[];
}
const sha256 = (bytes: Uint8Array) =>
  createHash("sha256").update(bytes).digest("hex");
/** Original synthetic pixels only. No real assessment, commercial art or binary files. */
export async function createSyntheticFixture(
  engine: "dimensions" | "archetype" = "archetype",
): Promise<SyntheticFixture> {
  const productId = `synthetic-${engine}`;
  const version = "1.0.0";
  const ref = (id: string): ContentReference => ({ id, productId, version });
  const component = (id: string) => ({
    id,
    version,
    propsSchemaVersion: version,
  });
  const assets: SyntheticFixture["assets"] = [];
  const resources: QuizPackContent["resources"] = [];
  for (const [i, format] of ["png", "jpg", "webp", "png"].entries()) {
    const width = 8 + i;
    const height = 7 + i;
    const pixels = Buffer.alloc(width * height * 3);
    for (let p = 0; p < pixels.length; p++) pixels[p] = (p * 17 + i * 41) % 256;
    const pipeline = sharp(pixels, { raw: { width, height, channels: 3 } });
    const bytes = await (
      format === "jpg"
        ? pipeline.jpeg()
        : format === "webp"
          ? pipeline.webp()
          : pipeline.png()
    ).toBuffer();
    const id = i === 0 ? "neutral-cover" : `portrait-${i}`;
    const path = `assets/${id}.${format}`;
    const mediaType =
      format === "jpg"
        ? "image/jpeg"
        : format === "webp"
          ? "image/webp"
          : "image/png";
    assets.push({ path, bytes });
    resources.push({
      ...ref(id),
      path,
      mediaType,
      bytes: bytes.length,
      sha256: sha256(bytes),
      width,
      height,
      purpose: i === 0 ? "cover" : "portrait",
      source: {
        kind: "original",
        attribution: "QuizForge synthetic test pixel generator",
        evidence:
          "Pixels generated by the committed fixture helper; test data only.",
      },
      license: {
        commercialUse: true,
        redistribution: true,
        evidence:
          "Original synthetic test pixels; declaration only, no commercial artwork approval.",
      },
      approval: "pending",
    });
  }
  const resultRefs = ["low", "middle", "high"].map(ref);
  const dimensionRefs = ["pace", "focus"].map(ref);
  const states = [
    "cover",
    "question",
    "resume",
    "result",
    "report",
    "poster",
  ] as const;
  const componentIds = [
    "folio-cover",
    "folio-question",
    "folio-resume",
    "cabinet-result",
    "folio-report",
    "folio-poster",
  ];
  const layouts = Object.fromEntries(
    states.map((state, i) => [
      state,
      {
        component: component(componentIds[i]!),
        props: {
          heading: `Synthetic ${state}`,
          body: "Synthetic contract fixture; no assessment conclusion.",
          density: "comfortable" as const,
          showProgress: state === "question",
        },
        resourceRefs: [ref("neutral-cover")],
      },
    ]),
  ) as QuizPackContent["layouts"];
  const normalization: QuizPackContent["rules"]["normalization"] = {
    kind: "linear-to-0-100",
    bounds: dimensionRefs.map((dimensionRef) => ({
      dimensionRef,
      min: 0,
      max: 4,
    })),
  };
  const common = {
    aggregation: "sum" as const,
    normalization,
    tieBreak: "result-order" as const,
    resultOrder: resultRefs,
  };
  const content: QuizPackContent = {
    schemaVersion: "quizpack-content.v1",
    kind: "synthetic",
    product: {
      productId,
      slug: productId,
      title: `Synthetic ${engine} contract`,
      categoryId: "synthetic",
      tags: ["test-only"],
    },
    contentVersion: version,
    visualVersion: version,
    reportVersion: version,
    resourceVersion: version,
    componentVersion: version,
    engine: { id: engine, version },
    dimensions: dimensionRefs.map((dimension) => ({
      ...dimension,
      label: `Synthetic ${dimension.id}`,
    })),
    questions: ["first", "second"].map((id) => ({
      ...ref(id),
      prompt: `Synthetic ${id} question`,
      options: [0, 1, 2].map((value) => ({
        ...ref(`${id}-option-${value}`),
        label: `Synthetic choice ${value}`,
        contributions: dimensionRefs.map((dimensionRef) => ({
          dimensionRef,
          value,
        })),
      })),
    })),
    rules:
      engine === "archetype"
        ? {
            ...common,
            kind: "archetype",
            distance: "squared-euclidean",
            profiles: resultRefs.map((resultRef, i) => ({
              resultRef,
              targets: dimensionRefs.map((dimensionRef) => ({
                dimensionRef,
                value: i * 50,
              })),
            })),
          }
        : {
            ...common,
            kind: "dimensions",
            profiles: resultRefs.map((resultRef, i) => ({
              resultRef,
              ranges: dimensionRefs.map((dimensionRef) => ({
                dimensionRef,
                min: [0, 25, 75][i]!,
                max: [24, 74, 100][i]!,
              })),
            })),
          },
    results: resultRefs.map((result, i) => ({
      ...result,
      label: `Synthetic ${result.id}`,
      portraitRef: ref(`portrait-${i + 1}`),
      reportTemplateRef: ref(`report-${result.id}`),
      witness: {
        status: "declared-not-executed",
        answers: ["first", "second"].map((id) => ({
          questionRef: ref(id),
          optionRef: ref(`${id}-option-${i}`),
        })),
      },
    })),
    reportTemplates: resultRefs.map((result) => ({
      ...ref(`report-${result.id}`),
      mode: "DETERMINISTIC",
      component: component("folio-report"),
      baseline: {
        title: "Synthetic baseline",
        summary: "This is a complete structural baseline for testing only.",
        strengths: ["Synthetic strength"],
        tensions: ["Synthetic tension"],
        reflection: "Which synthetic choice did you select?",
        disclaimer:
          "Synthetic entertainment fixture; not a diagnosis or a validated assessment.",
      },
    })),
    layouts,
    resources,
  };
  const contentBytes = Buffer.from(JSON.stringify(content));
  const manifest: QuizPackManifest = {
    schemaVersion: "quizpack.v1",
    packId: `fixture-${engine}`,
    packVersion: version,
    productId,
    contentSchemaVersion: content.schemaVersion,
    engine: content.engine,
    components: DEFAULT_COMPATIBILITY_POLICY.components.map((value) => ({
      ...value,
    })),
    files: [
      {
        path: "content.json",
        mediaType: "application/json",
        bytes: contentBytes.length,
        sha256: sha256(contentBytes),
      },
      ...resources.map((resource) => ({
        path: resource.path,
        mediaType: resource.mediaType,
        bytes: resource.bytes,
        sha256: resource.sha256,
      })),
    ],
  };
  return { content, contentBytes, manifest, assets };
}
